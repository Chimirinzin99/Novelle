-- Creates the profile row when someone signs up (data from sign-up metadata).
-- Note: profiles.full_name is NOT NULL, so creating a user in the Supabase
-- dashboard without full_name metadata fails - register through the app.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  insert into public.profiles (id, full_name, email, programme_id, role)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.email,
    (new.raw_user_meta_data->>'programme_id')::bigint,
    'student'
  );
  return new;
end;
$function$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- True if the logged-in user's account is active. Used by every
-- "Active accounts only" RLS policy, so authenticated must be able to call it.
create or replace function public.is_active_user()
returns boolean
language sql
stable
security definer
set search_path to ''
as $function$
  select coalesce(
    (select p.is_active from public.profiles p where p.id = auth.uid()),
    false
  );
$function$;

-- Like counts for a list of resources (students can only read their own
-- favourites through RLS, so the totals come from this function).
create or replace function public.get_like_counts(p_resource_ids bigint[])
returns table(resource_id bigint, likes bigint)
language sql
stable
security definer
set search_path to ''
as $function$
  select f.resource_id, count(*)::bigint as likes
  from public.favourites f
  where public.is_active_user()
    and f.resource_id = any (p_resource_ids)
  group by f.resource_id;
$function$;

-- Approves a pending submission in one transaction: copies it into
-- resources and marks the submission approved. Called by the backend.
create or replace function public.approve_submission(
  p_submission_id bigint, p_module_id bigint, p_reviewer uuid)
returns public.resources
language plpgsql
set search_path to 'public'
as $function$
declare
  s public.resource_submissions;
  m public.modules;
  r public.resources;
begin
  -- Lock the row so two admins can't approve the same submission at once.
  select * into s from public.resource_submissions
  where id = p_submission_id for update;

  if not found then raise exception 'SUBMISSION_NOT_FOUND'; end if;
  if s.status <> 'pending' then raise exception 'SUBMISSION_NOT_PENDING'; end if;

  select * into m from public.modules where id = p_module_id;

  if not found or not m.active then raise exception 'MODULE_NOT_FOUND'; end if;
  if m.programme_id <> s.programme_id then raise exception 'MODULE_WRONG_PROGRAMME'; end if;

  insert into public.resources (
    topic, title, type, programme_id, module_id, module_code, module_name,
    year, semester, file_path, uploaded_by, submission_id,
    author_type, author_name, is_solved
  )
  values (
    s.title, s.title, s.type, s.programme_id, m.id, m.module_code, m.module_name,
    m.year, m.semester, s.file_path, s.submitted_by, s.id,
    s.author_type, s.author_name, s.is_solved
  )
  returning * into r;

  update public.resource_submissions
  set status = 'approved', module_id = m.id, year = m.year, semester = m.semester,
      rejection_reason = null, reviewed_by = p_reviewer, reviewed_at = now()
  where id = s.id;

  return r;
end;
$function$;

-- Counts a failed login and locks the email after too many failures.
-- Called by the backend (service key) only.
create or replace function public.record_failed_login(
  p_email text, p_max_failures integer, p_window_minutes integer, p_lock_minutes integer)
returns table(failed_count integer, locked_until timestamptz, just_locked boolean)
language plpgsql
set search_path to ''
as $function$
#variable_conflict use_column
declare
  r public.login_attempts;
begin
  insert into public.login_attempts as a (email, failed_count, last_failed_at)
  values (p_email, 1, now())
  on conflict (email) do update
  set failed_count = case
        when a.locked_until is not null and a.locked_until <= now() then 1
        when a.last_failed_at < now() - make_interval(mins => p_window_minutes) then 1
        else a.failed_count + 1
      end,
      locked_until = case
        when a.locked_until is not null and a.locked_until <= now() then null
        else a.locked_until
      end,
      last_failed_at = now()
  returning a.* into r;

  if r.failed_count >= p_max_failures and r.locked_until is null then
    update public.login_attempts as a
    set locked_until = now() + make_interval(mins => p_lock_minutes)
    where a.email = p_email
    returning a.* into r;
    return query select r.failed_count, r.locked_until, true;
  else
    return query select r.failed_count, r.locked_until, false;
  end if;
end;
$function$;

