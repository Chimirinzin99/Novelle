-- 5. Storage
-- ---------------------------------------------------------------------
-- Private bucket "resources" (not public), file size limit 4 MB
-- (4194304 bytes), no MIME restriction at bucket level (the backend
-- checks for PDFs). Files are read through signed URLs.
--   submissions/<user_id>/...  student uploads waiting for review
--   other paths                files uploaded by admins / published files

create policy "Active accounts only" on storage.objects
  as restrictive for all to authenticated
  using (public.is_active_user()) with check (public.is_active_user());

create policy "Logged-in users can view published resource files" on storage.objects
  for select to authenticated
  using (bucket_id = 'resources'
         and exists (select 1 from public.resources r where r.file_path = objects.name));

create policy "Students can view their own submission files" on storage.objects
  for select to authenticated
  using (bucket_id = 'resources'
         and (storage.foldername(name))[1] = 'submissions'
         and (storage.foldername(name))[2] = auth.uid()::text);

create policy "Admins can view resource files" on storage.objects
  for select to authenticated
  using (bucket_id = 'resources'
         and (storage.foldername(name))[1] = 'submissions'
         and exists (select 1 from public.profiles p
                     where p.id = auth.uid()
                       and (p.role = 'super_admin'
                            or (p.role = 'programme_admin'
                                and p.programme_id = (select rs.programme_id
                                                      from public.resource_submissions rs
                                                      where rs.file_path = objects.name
                                                      limit 1)))));
