-- The ten study programmes (e.g. BE Software Engineering).
create table public.programmes (
  id          bigint generated by default as identity primary key,
  name        text not null,
  short_name  text not null unique
);

-- One row per user, created by the handle_new_user() trigger on sign-up.
-- There are no "lecturer" roles in the database: lecturers are students
-- with name-style emails until a super admin promotes them.
create table public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  full_name     text not null,
  email         text not null unique,
  programme_id  bigint references public.programmes(id),
  role          text not null default 'student',
  created_at    timestamptz default now(),
  is_active     boolean not null default true,

  constraint profiles_role_check
    check (role in ('student', 'programme_admin', 'super_admin')),
  -- Programme admins need a programme; super admins have none.
  constraint profiles_role_programme_check
    check ((role = 'programme_admin' and programme_id is not null)
        or (role = 'super_admin' and programme_id is null)
        or (role = 'student')),
  constraint profiles_email_rub_check
    check (email ~* '@rub\.edu\.bt$'),
  -- Student number (digits) or name-style address, ending .cst@rub.edu.bt
  constraint profiles_email_cst_check
    check (email ~* '^([0-9]+|[a-z]+([._-][a-z]+)*)\.cst@rub\.edu\.bt$')
);

-- Modules (subjects) of a programme. Inactive modules are hidden from students.
create table public.modules (
  id            bigint generated by default as identity primary key,
  programme_id  bigint not null references public.programmes(id) on delete cascade,
  module_code   text not null,
  module_name   text not null,
  year          integer not null,
  semester      integer not null,
  created_at    timestamptz default now(),
  active        boolean not null default true
);

-- Student uploads waiting for review (pending / approved / rejected).
create table public.resource_submissions (
  id                bigint generated by default as identity primary key,
  title             text not null,
  type              text not null,
  programme_id      bigint not null references public.programmes(id) on delete cascade,
  module_id         bigint references public.modules(id) on delete set null,
  year              integer,
  semester          integer,
  file_path         text not null,
  submitted_by      uuid references public.profiles(id) on delete set null,
  status            text not null default 'pending',
  created_at        timestamptz default now(),
  rejection_reason  text,
  reviewed_by       uuid references public.profiles(id) on delete set null,
  reviewed_at       timestamptz,
  author_type       text,
  author_name       text,
  is_solved         boolean not null default false,

  constraint resource_submissions_type_check
    check (type in ('note', 'question_paper', 'assignment')),
  constraint resource_submissions_status_check
    check (status in ('pending', 'approved', 'rejected')),
  constraint resource_submissions_rejection_reason_check
    check (rejection_reason is null or rejection_reason in (
      'wrong_programme_or_module', 'duplicate', 'poor_quality_scan',
      'incomplete', 'not_academic', 'copyright_concern')),
  constraint resource_submissions_author_type_check
    check (author_type is null or author_type in ('self', 'other', 'unknown')),
  constraint resource_submissions_author_name_check
    check ((author_name is null or char_length(btrim(author_name)) between 1 and 80)
       and (author_type is distinct from 'other' or author_name is not null)
       and (author_type in ('self', 'other') or author_name is null))
);

-- Published resources (PDF notes / question papers / assignments, and videos).
-- module_code and module_name are copies of the module's values (kept in
-- sync by the backend) so search and cards don't need a join.
create table public.resources (
  id             bigint generated by default as identity primary key,
  title          text,
  type           text not null,
  programme_id   bigint not null references public.programmes(id) on delete cascade,
  year           integer not null,
  semester       integer not null,
  file_path      text,
  uploaded_by    uuid references public.profiles(id) on delete set null,
  created_at     timestamptz default now(),
  topic          text not null,
  module_name    text,
  module_id      bigint references public.modules(id) on delete set null,
  submission_id  bigint references public.resource_submissions(id) on delete set null,
  video_id       text,
  author_type    text,
  author_name    text,
  is_solved      boolean not null default false,
  module_code    text,

  constraint resources_type_check
    check (type in ('note', 'question_paper', 'assignment', 'video')),
  -- Videos have an 11-character YouTube id and no file; everything else has a file.
  constraint resources_content_check
    check ((type = 'video' and video_id ~ '^[A-Za-z0-9_-]{11}$' and file_path is null)
        or (type <> 'video' and video_id is null and file_path is not null)),
  constraint resources_author_type_check
    check (author_type is null or author_type in ('self', 'other', 'unknown')),
  constraint resources_author_name_check
    check ((author_name is null or char_length(btrim(author_name)) between 1 and 80)
       and (author_type is distinct from 'other' or author_name is not null)
       and (author_type in ('self', 'other') or author_name is null))
);

