-- Deactivated accounts see nothing (restrictive = must ALSO pass).
create policy "Active accounts only" on public.modules
  as restrictive for all to authenticated
  using (public.is_active_user()) with check (public.is_active_user());
create policy "Active accounts only" on public.resource_submissions
  as restrictive for all to authenticated
  using (public.is_active_user()) with check (public.is_active_user());
create policy "Active accounts only" on public.resources
  as restrictive for all to authenticated
  using (public.is_active_user()) with check (public.is_active_user());
create policy "Active accounts only" on public.favourites
  as restrictive for all to authenticated
  using (public.is_active_user()) with check (public.is_active_user());
create policy "Active accounts only" on public.notifications
  as restrictive for all to authenticated
  using (public.is_active_user()) with check (public.is_active_user());

-- programmes: public (the sign-up form needs the list).
create policy "Anyone can view programmes" on public.programmes
  for select to anon, authenticated using (true);

-- profiles: own row only. No update policy on purpose (RLS cannot limit
-- columns, so a user could change their own role) - name changes go
-- through PATCH /api/auth/me/name on the backend.
create policy "Users can read their own profile" on public.profiles
  for select to authenticated using (id = auth.uid());

-- modules
create policy "Users can view active modules of their own programme" on public.modules
  for select to authenticated
  using (active and programme_id = (select p.programme_id from public.profiles p where p.id = auth.uid()));
create policy "Programme admins can view their programme modules" on public.modules
  for select to authenticated
  using (exists (select 1 from public.profiles p
                 where p.id = auth.uid()
                   and (p.role = 'super_admin'
                        or (p.role = 'programme_admin' and p.programme_id = modules.programme_id))));

-- resource_submissions
create policy "Students can view their own submissions" on public.resource_submissions
  for select to authenticated using (submitted_by = auth.uid());
create policy "Admins can view allowed submissions" on public.resource_submissions
  for select to authenticated
  using (exists (select 1 from public.profiles p
                 where p.id = auth.uid()
                   and (p.role = 'super_admin'
                        or (p.role = 'programme_admin' and p.programme_id = resource_submissions.programme_id))));

-- resources
create policy "Logged-in users can view resources" on public.resources
  for select to authenticated using (true);

-- favourites: students like/unlike directly from the browser.
create policy "Users can view their own favourites" on public.favourites
  for select to authenticated using (auth.uid() = user_id);
create policy "Users can add their own favourites" on public.favourites
  for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can remove their own favourites" on public.favourites
  for delete to authenticated using (auth.uid() = user_id);

-- notifications
create policy "Users can read their own notifications" on public.notifications
  for select to authenticated using (user_id = auth.uid());
create policy "Users can mark their own notifications read" on public.notifications
  for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());


